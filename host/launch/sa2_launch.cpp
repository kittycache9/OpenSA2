std::string home_rel(const std::string& p) {
    if (!g_home.empty() && p.compare(0, g_home.size(), g_home) == 0 &&
        (p.size() == g_home.size() || p[g_home.size()] == '/'))
        return "~" + p.substr(g_home.size());
    return p;
}

std::string fold(const std::string& p) {
    std::string s = p;
    for (char& c : s) {
        if (c == '\\') c = '/';
        else if (c >= 'A' && c <= 'Z') c = char(c - 'A' + 'a');
    }
    return s;
}

bool absolute(const std::string& p) { return !p.empty() && (p[0] == '/' || (p.size() > 2 && p[1] == ':')); }

