// `root`/`rel` with each component matched case-blind, as the runtime resolves a guest path
// (runtime/sa2_files.c); "" when some component is absent.
std::string find_folded(const std::string& root, const std::string& rel) {
    std::string at = root;
    size_t from = 0;
    while (from <= rel.size()) {
        size_t slash = rel.find('/', from);
        const std::string part = rel.substr(from, slash == std::string::npos ? std::string::npos : slash - from);
        from = slash == std::string::npos ? rel.size() + 1 : slash + 1;
        if (part.empty()) continue;
        std::vector<std::string> names;
        if (!sa2p::list_dir(at, names)) return "";
        std::string hit;
        for (const std::string& n : names)
            if (fold(n) == fold(part)) hit = n;
        if (hit.empty()) return "";
        at += "/" + hit;
    }
    return at;
}

// The files in the folder `rel` under `root` (case-blind), sorted; none when it is absent.
std::vector<std::string> files_in(const std::string& root, const std::string& rel) {
    std::vector<std::string> out, names;
    const std::string dir = find_folded(root, rel);
    if (dir.empty() || !sa2p::list_dir(dir, names)) return out;
    for (const std::string& n : names)
        if (exists_file(dir + "/" + n)) out.push_back(n);
    std::sort(out.begin(), out.end());
    return out;
}

bool same_folder(const std::string& a, const std::string& b) {
    std::string ra, rb;
    if (sa2p::real_path(a, ra) && sa2p::real_path(b, rb)) return ra == rb;
    return a == b;
}

// Waits for `p` at most `s` seconds, and stops waiting at once when a second interrupt (Ctrl-C)
// asks the launcher to stop now. True when it has exited.
bool wait_or_cancel(sa2l::Proc& p, double s) {
    const double t0 = sa2p::monotonic_seconds();
    while (!sa2l::wait_exit(p, 0.1)) {
        if (sa2l::interrupts() >= 2 || sa2p::monotonic_seconds() - t0 >= s) return false;
    }
    return true;
}

void stop_game(sa2l::Proc& game, std::string& how) {
    if (!game.running) return;
    sa2l::send_signal(game, sa2l::Signal::Terminate);
    if (wait_or_cancel(game, kStopGrace)) {
        how = "SIGTERM";
        return;
    }
    if (sa2l::interrupts() < 2) {
        sa2l::send_signal(game, sa2l::Signal::Terminate);
        if (wait_or_cancel(game, kKillGrace)) {
            how = "second SIGTERM";
            return;
        }
    }
    how = sa2l::interrupts() >= 2 ? "SIGKILL (a second interrupt)" : "SIGKILL";
    sa2l::send_signal(game, sa2l::Signal::Kill, true);
    sa2l::wait_exit(game, 10);
}

