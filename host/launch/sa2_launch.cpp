struct Env {
    std::vector<std::pair<std::string, std::string>> kv;
    void set(const std::string& k, const std::string& v) {
        for (auto& e : kv)
            if (e.first == k) {
                e.second = v;
                return;
            }
        kv.emplace_back(k, v);
    }
    void drop_prefix(const std::string& p) {
        kv.erase(std::remove_if(kv.begin(), kv.end(),
                                [&](const auto& e) { return e.first.compare(0, p.size(), p) == 0; }),
                 kv.end());
    }
    void drop(const std::string& k) {
        kv.erase(std::remove_if(kv.begin(), kv.end(), [&](const auto& e) { return e.first == k; }), kv.end());
    }
    const std::string* find(const std::string& k) const {
        for (const auto& e : kv)
            if (e.first == k) return &e.second;
        return nullptr;
    }
};

bool read_env_file(const std::string& path, Env& env, std::string* error) {
    std::string text;
    if (!sa2p::read_file(path, text)) {
        *error = "no game settings at " + path;
        return false;
    }
    std::istringstream in(text);
    std::string line;
    while (std::getline(in, line)) {
        if (line.empty() || line[0] == '#') continue;
        size_t eq = line.find('=');
        if (eq == std::string::npos || line.compare(0, 4, "SA2_") != 0) {
            *error = path + ": a line that is no SA2_ setting: " + line;
            return false;
        }
        env.set(line.substr(0, eq), line.substr(eq + 1));
    }
    return true;
}

