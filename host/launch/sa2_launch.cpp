// Where the player's key sender serves its own pipe (sa2l::player_serves_keys: Windows, whose
// sender is a named pipe's server, host/player/input.cpp), the launcher is its reader. It opens the
// pipe as a client once the player has made it (after its window is up) and hands every byte on,
// in order and as soon as it arrives, to the game's keyboard pipe, which the launcher holds for the
// whole session, so the game never reads end of file (every key up) while the launcher lives, as
// the FIFO the launcher holds O_RDWR does on POSIX. The bytes are the sender's records, keyboard
// (SA2K) and gamepad (SA2P), whole and in order (runtime/sa2_dinput.h), and the game reassembles a
// record a read splits. A connection the sender ends (it closes at the end request, or listens
// again after an error) is opened again while the session lasts.
struct KeyForward {
    std::atomic<bool> done{false};
    std::atomic<uint64_t> bytes{0}, connections{0}, write_failures{0};
    std::string error;                    // written by the thread; read after it is joined

    void run(const std::string& path, sa2l::Fd game_keys) {
        std::vector<char> buf(1u << 16);
        while (!done.load()) {
            bool absent = false;
            std::string why;
            sa2l::Fd c = sa2l::open_pipe_client(path, &absent, &why);
            if (c == sa2l::kNoFd) {
                if (!absent) {
                    error = why;
                    return;
                }
                sa2l::sleep_ms(10);
                continue;
            }
            connections++;
            for (;;) {
                const long n = sa2l::read_wait(c, buf.data(), buf.size(), 100);
                if (n > 0) {
                    if (sa2l::write_all(game_keys, buf.data(), size_t(n))) bytes += uint64_t(n);
                    else write_failures++;
                    continue;
                }
                if (n == -1 && !done.load()) continue;
                break;                        // end of file, an error, or the session over
            }
            sa2l::close_fd(c);
        }
    }
};

