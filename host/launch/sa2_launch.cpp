// A --play-res value as runtime/sa2_widescreen.c takes SA2_PLAY_RES: WxH, each 320 to 16384.
bool play_res_ok(const std::string& v) {
    const size_t x = v.find_first_of("xX");
    auto dim = [](const std::string& d) {
        if (d.empty() || d.size() > 5 || d.find_first_not_of("0123456789") != std::string::npos) return false;
        const unsigned long n = std::strtoul(d.c_str(), nullptr, 10);
        return n >= 320 && n <= 16384;
    };
    return x != std::string::npos && dim(v.substr(0, x)) && dim(v.substr(x + 1));
}

// The primary display's desktop size, from the release's SDL3 loaded at run time as the dialogs
// load it (sa2d::sdl_library): SDL_InitSubSystem(SDL_INIT_VIDEO) on `driver` (the player's
// SDL_VIDEO_DRIVER, when one is named), SDL_GetPrimaryDisplay and SDL_GetDesktopDisplayMode, then
// SDL_QuitSubSystem. SDL_DisplayMode is declared as SDL_video.h defines it (SDL 3.4.16, the pinned
// release; SDL3 keeps its ABI within the major version). False, with *why, when there is no
// display to ask: SDL's offscreen or dummy driver, no DISPLAY or WAYLAND_DISPLAY (Linux), no
// SDL3, or SDL's own refusal.
bool primary_display(const std::string& driver, uint32_t& w, uint32_t& h, std::string* why) {
    const std::string d = fold(driver.empty() ? sa2p::env("SDL_VIDEO_DRIVER") : driver);
    if (d == "offscreen" || d == "dummy") {
        *why = "SDL's " + d + " driver has no display";
        return false;
    }
#ifndef _WIN32
    if (sa2p::env("DISPLAY").empty() && sa2p::env("WAYLAND_DISPLAY").empty()) {
        *why = "there is no display (DISPLAY and WAYLAND_DISPLAY are unset)";
        return false;
    }
#endif
    struct DisplayMode {
        uint32_t displayID;
        uint32_t format;
        int w, h;
        float pixel_density, refresh_rate;
        int refresh_rate_numerator, refresh_rate_denominator;
        void* internal;
    };
    constexpr uint32_t kInitVideo = 0x00000020u;          // SDL_INIT_VIDEO
    const std::string lib = sa2d::sdl_library(sa2l::self_dir());
#ifdef _WIN32
    // LoadLibrary takes backslashes alone; the folder's own copy, its dependencies from there too.
    std::string native = lib;
    for (char& c : native)
        if (c == '/') c = '\\';
    const int n = MultiByteToWideChar(CP_UTF8, 0, native.data(), int(native.size()), nullptr, 0);
    std::wstring wide(size_t(n > 0 ? n : 0), L'\0');
    if (n > 0) MultiByteToWideChar(CP_UTF8, 0, native.data(), int(native.size()), &wide[0], n);
    HMODULE handle = LoadLibraryExW(wide.c_str(), nullptr, LOAD_WITH_ALTERED_SEARCH_PATH);
    auto sym = [&](const char* name) { return reinterpret_cast<void*>(GetProcAddress(handle, name)); };
#else
    void* handle = dlopen(lib.c_str(), RTLD_NOW | RTLD_LOCAL);
    auto sym = [&](const char* name) { return dlsym(handle, name); };
#endif
    if (!handle) {
        *why = "cannot load " + lib;
        return false;
    }
    using InitSub = bool (*)(uint32_t);
    using QuitSub = void (*)(uint32_t);
    using Primary = uint32_t (*)();
    using Desktop = const DisplayMode* (*)(uint32_t);
    using GetErr = const char* (*)();
    using SetHint = bool (*)(const char*, const char*);
    auto init = reinterpret_cast<InitSub>(sym("SDL_InitSubSystem"));
    auto quit = reinterpret_cast<QuitSub>(sym("SDL_QuitSubSystem"));
    auto primary = reinterpret_cast<Primary>(sym("SDL_GetPrimaryDisplay"));
    auto desktop = reinterpret_cast<Desktop>(sym("SDL_GetDesktopDisplayMode"));
    auto error = reinterpret_cast<GetErr>(sym("SDL_GetError"));
    auto hint = reinterpret_cast<SetHint>(sym("SDL_SetHint"));
    if (!init || !quit || !primary || !desktop || !error || !hint) {
        *why = lib + " lacks the display calls";
        return false;
    }
    hint("SDL_NO_SIGNAL_HANDLERS", "1");      // the launcher keeps its own (sa2l::catch_interrupts)
    if (!driver.empty()) hint("SDL_VIDEO_DRIVER", driver.c_str());
    if (!init(kInitVideo)) {
        *why = std::string("SDL's video: ") + error();
        return false;
    }
    const uint32_t id = primary();
    const DisplayMode* m = id ? desktop(id) : nullptr;
    const bool ok = m && m->w > 0 && m->h > 0;
    if (ok) {
        const float density = m->pixel_density > 0 ? m->pixel_density : 1.0f;
        w = uint32_t(float(m->w) * density + 0.5f);
        h = uint32_t(float(m->h) * density + 0.5f);
    } else {
        *why = std::string("SDL gave no primary display: ") + error();
    }
    quit(kInitVideo);
    return ok;
}

