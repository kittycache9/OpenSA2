// A user file, by the installer's own rule (host/install sa2_install_extra_allowed): a top-level
// Config/*.cfg or Config/*.ini (the game reads .\Config\UserConfig.cfg, Keyboard.cfg and
// StageSelectConfig.ini there; the shipped resource/gd_PC/StageSelectConfig.ini is no user file,
// is not in the table, and an open of it fails the selftest by name), or a save under
// resource/gd_PC/SAVEDATA/.
bool user_file(const std::string& folded) {
    auto ends = [&](const char* e) {
        size_t n = std::strlen(e);
        return folded.size() >= n && folded.compare(folded.size() - n, n, e) == 0;
    };
    if (folded.compare(0, 7, "config/") == 0 && (ends(".cfg") || ends(".ini")) &&
        folded.find('/', 7) == std::string::npos)
        return true;
    return folded.compare(0, 24, "resource/gd_pc/savedata/") == 0;
}

RunCheck check_run(const std::string& path, const std::set<std::string>& table) {
    RunCheck c;
    std::string text;
    if (!sa2p::read_file(path, text, size_t(1) << 30)) {
        c.parse_error = "the game wrote no run record at " + home_rel(path);
        return c;
    }
    sa2j::Value d;
    if (!sa2j::parse(text, d, &c.parse_error)) return c;
    c.parsed = true;
    c.ok = d.at("ok").is_true();
    c.trap_note = d.at("trap").at("note").str();
    c.guest_exit = c.trap_note.find("ExitProcess") != std::string::npos;
    const sa2j::Value& cw = d.at("d3d9").at("closed_world");
    c.world_mode = cw.at("mode").str();
    c.trap_mode = c.world_mode == "trap";
    c.automated = cw.at("automated_session").is_true();
    c.unlisted_methods = cw.at("unlisted_methods").num();
    c.unlisted_calls = cw.at("unlisted_calls").num();
    const sa2j::Value& exe = d.at("exe");
    c.exe_kind = exe.at("kind").str();
    c.exe_kind_env = exe.at("kind_env").str();
    c.overlay_loaded = exe.at("overlay").at("loaded").is_true();
    c.readset_sha256 = exe.at("overlay").at("table").at("readset_sha256").str();
    c.overlay_refusal = exe.at("overlay").at("refusal").str();
    const sa2j::Value& files = d.at("files");
    c.files_ready = files.at("ready").is_true();
    c.read_root = files.at("read_root").str();
    c.write_root = files.at("write_root").str();
    if (const sa2j::Value* n = files.at("stats").get("resolves")) c.resolves_counted = n->num();
    if (const sa2j::Value* n = files.at("stats").get("opens")) c.opens_counted = n->num();
    c.resolutions_logged = files.at("resolutions").a.size();
    for (const auto& r : files.at("resolutions").a) {
        const std::string status = r.at("status").str(), rel = r.at("rel").str();
        if (status == "not-found") {
            c.not_found++;
            if (table.count(fold(rel))) c.table_not_found.push_back(rel);
        } else if (status != "ok") {
            c.refused.push_back(rel + " (" + status + ")");
        }
    }
    std::set<std::string> seen;
    for (const auto& o : files.at("opened").a) {
        c.opened++;
        const std::string rel = o.at("rel").str(), f = fold(rel);
        if (table.count(f) || user_file(f)) continue;
        if (seen.insert(f).second) c.opened_unverified.push_back(rel);
    }
    return c;
}

