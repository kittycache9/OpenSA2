// Reads SA2_LAUNCH_TICKS as the game appends to it (tools/s7/release_build.py observer_source).
class TickTail {
public:
    explicit TickTail(std::string path) : path_(std::move(path)) {}
    // New whole lines since the last call.
    std::vector<std::string> lines() {
        std::vector<std::string> out;
        if (!f_) f_ = std::fopen(path_.c_str(), "rb");
        if (!f_) return out;
        char buf[1 << 16];
        size_t n;
        while ((n = std::fread(buf, 1, sizeof buf, f_)) > 0) part_.append(buf, n);
        // A seek to where it is, not clearerr alone: it clears end of file and drops the stream's
        // buffer, so the next read asks the file again. The Windows C runtime's stream keeps
        // returning nothing after clearerr while the game appends (measured under Wine,
        // 2026-10-11: the launcher read three rows of thousands).
        std::fseek(f_, 0, SEEK_CUR);
        size_t at = 0, nl;
        while ((nl = part_.find('\n', at)) != std::string::npos) {
            out.push_back(part_.substr(at, nl - at));
            at = nl + 1;
        }
        part_.erase(0, at);
        return out;
    }
    ~TickTail() {
        if (f_) std::fclose(f_);
    }

private:
    std::string path_, part_;
    FILE* f_ = nullptr;
};

std::vector<std::string> split_tabs(const std::string& s) {
    std::vector<std::string> out;
    size_t at = 0, t;
    while ((t = s.find('\t', at)) != std::string::npos) {
        out.push_back(s.substr(at, t - at));
        at = t + 1;
    }
    out.push_back(s.substr(at));
    return out;
}

