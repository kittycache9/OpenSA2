// sa2_launch.cpp: sa2recomp, the launcher of the prebuilt release (S7). It replaces
// tools/s5/play_live.py's Python orchestration for the product.
//
//   sa2recomp [--host sdl3-gpu|dxvk-native] [--no-pace] [--no-sound] [--no-verify] [--out DIR]
//             [--no-widescreen | --play-res WxH] [--player-arg ARG ...]
//   sa2recomp --selftest [--frames N] [--record R.runrec] [--host H] [--out DIR] [--timeout S]
//             [--video-driver NAME] [--pace]
//
// What a launch does, in order (each step refuses by name, and nothing is half-started):
//
//  1. The release: this executable's directory is <release>/bin, beside the game (sa2-game),
//     the players, the installer (sa2-install), lib/ and share/ (tools/s7/release_build.py).
//  2. The installation: the installer's config (host/install/sa2_config.h,
//     $XDG_CONFIG_HOME/sa2recomp/sa2recomp.cfg). Its read_root becomes SA2_INSTALL, its overlay
//     SA2_VFS_WRITE_ROOT and its exe the shipped sonic2app.exe the game loads as-is
//     (SA2_EXE_KIND=shipped, the user's DRM ruling). All three must be absolute and exist, so the
//     runtime never falls back to its cwd-relative defaults (runtime/sa2_files.c). Unless
//     --no-verify, `sa2-install --verify` runs first (the quick check, a full one on any
//     difference), and a launch whose installation no longer verifies does not start.
//     The first play with no config installs first (first_run), so a person's first launch needs
//     no other step: the installer's Steam route (`sa2-install --source steam --yes`, the
//     steam-autodiscovery route); when Steam has no copy (or more than one), a message box asks
//     for the game's folder or a ZIP of it, and SDL's picker takes it (sa2_dialog.h) to the folder
//     or zip route (`--source folder PATH --yes`, `--source zip FILE --yes`). A refusal (a changed
//     or missing file, no game there) is the installer's own message, in an error box, and the
//     launch ends with the installer's exit code. With no picker to show (Linux with no display,
//     or neither the desktop portal nor zenity) it says what to run instead and ends with 4.
//     Every step's output and record are kept under <data>/sa2recomp/first-run/<stamp>-<pid>/, and
//     the launch record names them (`first_run`). The selftest never installs: its routes install
//     explicitly, and with no config it refuses as before.
//  3. The session: a folder of its own under the data folder (<data>/sessions/<id>, the overlay's
//     parent; --out names another), holding the two FIFOs, the logs and the records. The game
//     runs with it as its working directory.
//  4. The game (bin/sa2-game, the lifted image with the recorder) with share/game.env's settings
//     (play_live's boot session's, generated by release_build.py) and the session's: the stream
//     into the game FIFO (SA2_REC_TRACE), the keyboard from the input FIFO
//     (SA2_INPUT_DI_SOURCE: the game's own DirectInput keyboard, runtime/sa2_dinput.h), its log
//     (SA2_INPUT_DI_LOG), the launch observer's table (SA2_LAUNCH_TICKS), the runtime's stall watch
//     (SA2_STALL_DUMP_MS=3000 unless game.env sets it: runtime/sa2_stall.h) and, paced on POSIX,
//     the read end of the pace pipe as descriptor 43 (SA2_REC_PACE_FD: sa2_relay.h, "Pace").
//  5. The player (--host's) with play_live's descriptors: --video-fd (the relay's pipe),
//     --cancel-fd (the launcher's way to stop it), --end-fd (its way to ask for the end), and,
//     except in the selftest, --input-path, so its window's keys reach the game through the input
//     FIFO. The launcher holds that FIFO open O_RDWR for the whole session, as play_live does: the
//     player's open never fails, and the game never reads end of file (every key up) because the
//     player is slow to start.
//  6. The relay (sa2_relay.h) hands the stream from the game's FIFO to the player, pacing the game
//     through the pace pipe, and nudges the game (SIGURG) when part of a frame waits a second for
//     the rest; its lines go to stderr and launcher.log.
//  7. The end. A close of the window (the player's end request), the player's exit, Ctrl-C, or
//     the selftest's verdict asks the game to stop: SIGTERM, which the runtime turns into WM_QUIT
//     at its next keyboard poll, so the guest leaves its loop through its own code and the probe
//     writes its run record; a second SIGTERM after kStopGrace, SIGKILL after kKillGrace. The
//     relay then ends with the stream, the player reads it to its END, and is cancelled through
//     --cancel-fd only if it has not finished kFeedGrace later.
//
// The default host is sdl3-gpu (host 2: the renderer on SDL3's GPU API, host/d3d9gpu): it is this
// project's own code with no third-party renderer to pin, it runs headless (SDL's offscreen
// driver) as its tests run it, and SDL's GPU API is the one renderer that reaches every release
// target (Vulkan here, Direct3D 12 on Windows, Metal on macOS, Vulkan on Android), where DXVK
// Native is Linux's alone. --host dxvk-native runs the first host (DXVK Native behind the recorded
// calls) the same way.
//
// On Windows (sa2_launch_win32.cpp) the FIFOs are named pipes the launcher serves, SIGTERM is a
// Ctrl-C into the game's own console, and host 2's player is given its channels by the pipes'
// names: the selftest's player reads its stream by path (it is cancelled by being ended); play's
// runs the interactive mode with --video-pipe, --cancel-pipe and --end-pipe in place of the three
// descriptors, and its end request (SIGUSR1) is a named event. Its key sender serves a pipe of
// its own (the player's "keys"), which the launcher reads and hands on, byte for byte, to the
// game's keyboard pipe, which the launcher holds for the whole session (KeyForward), so the
// window's keys and the player's gamepads reach the game as on Linux. Play paces to real time
// and plays the sound on SDL's default device, as on Linux.
//
// A person's launch sees what goes wrong. In play, an error that ends the launch is also shown in
// an error box (sa2_dialog.h), since a launch from a file manager or from Explorer has no terminal
// to read: not for a usage error, which only a command line makes, nor when a program reads the
// launcher's error stream (a pipe or a file: a runner, which has no person to close a box,
// sa2l::error_output_captured). The first run's own boxes (its question, the installer's refusal)
// are shown either way. Everything the launcher said is kept in the session's launcher.log.
//
// On Windows a launcher started alone in a console of its own (a double-click in Explorer makes
// one for it) gives that console up when the game starts (sa2l::release_own_console), so its
// window does not sit over the game's; one whose console a shell shares, or whose output is
// redirected (windows_play.py, windows_routes.py), keeps it, and the record says which
// (`console`).
//
// Full width (play only; runtime/sa2_widescreen.c, the user's request of 2026-10-12,
// Documentation/decisions/2026-10-12-S7-widescreen-pulled-forward.md): the game draws its back
// buffer at the primary display's aspect, so the player's window has no bars. Unless share/game.env
// sets SA2_PLAY_RES or SA2_PLAY_ASPECT, play sets SA2_PLAY_ASPECT to the primary display's W:H in
// pixels (primary_display: the release's SDL3, as the dialogs load it), and the runtime then
// widens the config's Width at its Height (a 2560x1080 display and a 1280x720 config: 1707x720).
// A display no wider than 4:3, or none (no DISPLAY or WAYLAND_DISPLAY, SDL's offscreen or dummy
// driver, no SDL3), sets nothing; on a 16:9 display the config's own 16:9 size is unchanged.
// --no-widescreen sets SA2_PLAY_RES=off and --play-res WxH that size, over game.env and the
// display both. The launcher says which, and the record keeps it (`widescreen`).
//
// Tweaks (play only; runtime/sa2_tweaks.h): changes to the game's own behaviour, each off by
// default, named in one setting, SA2_TWEAKS, a comma-separated list. On the desktop it is a line
// in share/game.env, which reaches the game as written (the launcher passes none of its own
// environment's SA2_ variables): SA2_TWEAKS=no-event-bars removes the black bars at the sides of
// in-engine cutscenes on a screen wider than 4:3. The player is given the same value, for the
// host's own tweaks (host/player/tweaks.h; runtime/sa2_tweaks.h lists the game's and the host's
// alike), and so is the launcher's reader, for those made here (host/launch/tweaks/<name>.cpp),
// whose line the launcher prints whenever the value is set ("sa2 host tweaks (launcher): ...").
// The selftest runs the game and the player as they are and drops the line for both, and so does
// a session whose --player-arg gives the player synthetic input (--synthetic-keys or
// --synthetic-input, sa2tw::kSyntheticFlags): that is a test run, whose player ignores its tweaks.
// A replay setting (SA2_REPLAY_TICKS or SA2_REPLAY_WORDS) in game.env turns every tweak off, as
// the game does: the launcher asks the game's environment, not its own, and gives the player that
// setting beside SA2_TWEAKS, so all three say "ignored in a replay". The launcher says what the
// game is given, the record keeps it (`tweaks`), and the game's own line saying which tweaks are
// on starts the session's game.log ("sa2 tweaks: ..."), the player's its player.err
// ("sa2 host tweaks (player): ...").
// With vanilla-profile among the names, the game, the player and the launcher's reader get
// SA2_TWEAKS=vanilla-profile alone, every other tweak off, and game.env keeps its list
// (host/launch/tweaks/vanilla-profile.cpp).
//
// --player-arg ARG (play only, repeatable) appends ARG to the player's command line: a
// diagnostic, as the player's own --synthetic-keys with its logs and --max-frames, which drives a
// play session with no person (host/launch/windows_play.py). The record names them. With either
// synthetic-input flag among them, game.env's SA2_TWEAKS is dropped (the header, "Tweaks").
//
// The selftest ("launched", G7's installer clause): the game must reach the title (GameMode 14,
// GameMode_Advertise, with CurrentMenu 0, Menus_TitleScreen: the addresses and values of
// Documentation/scripts/check_s5_exit.py STATE_WORDS), hold it while it presents --frames N
// frames, and then a scripted Enter (DIK 0x1C), written by the launcher into the input FIFO, the
// game's own keyboard path, must take it on. Measured on 2026-10-11: one Enter at the title opens
// File Select (CurrentMenu 9, Menus_FileSelect), and a second one there (NEW FILE, or the save)
// opens the main menu (CurrentMenu 1, Menus_Main), as the audio scenes' script found
// (tools/s5/audio_scenes.py KEYS["menu"]). So the selftest presses Enter at the title and again
// after File Select has presented kMenuFrames frames, at most kMaxEnters times, and passes when
// CurrentMenu 1 is reached. The game runs in the device's trap mode (an automated session:
// SA2_REC_COUNTS is counts.synthetic.json, runtime/sa2_d3d9.c automated_session), and the
// verdict also holds: the run record's closed world shows no method off the M7 list; no path the
// table holds was not found; every file the game opened from the installation is a table file
// or a user file (Config/*.cfg, a save), so the game ran only on verified files; the guest ended
// itself (ExitProcess) after the host's quit; the player ended with exit 0 and its report final.
// Nothing here needs a person or a window: SDL_VIDEO_DRIVER=offscreen unless --video-driver, for the
// default host. DXVK Native has no surface to present to under SDL's offscreen driver (measured
// 2026-10-11: the player crashes in its first Present), so a selftest on --host dxvk-native names a
// windowing driver (--video-driver x11 or wayland): a window on the desktop session that takes no
// input, since the selftest's keys go to the game through the input FIFO and the player is given
// no --input-path. The record says which (`player.window`).
//
// The selftest never writes the user's files: the game's write root is the session's own overlay
// (<session>/overlay), seeded with copies of the user's Config/*.cfg and Config/*.ini from the
// installation's overlay, so a selftest leaves no save in the overlay the game is played from and
// runs the same way the next time. Nor does it read the user's saves: the installation's own
// folder is read as in play except its resource/gd_PC/SAVEDATA (the original game's saves, on a
// folder someone has played from), which the runtime hides (SA2_VFS_HIDE_INSTALL_SAVES,
// runtime/sa2_files.c install_save_hidden), so the game runs the path the keys were measured on.
// Measured on 2026-10-11 with a save there: File Select lists the save selected, and Enter opens
// the file's own menu (the game's sub-state 5 at 0x01D7BB14, its cursor on the middle of three
// choices, which goes back to the list), so Enter alone never reaches the main menu; and the
// game reopens each save at every poll of its slots, every tenth frame, past the file log's
// bound. The record names the saves hidden (`read_root_saves`).
//
// The selftest also holds what it reads to be complete: the runtime's file log keeps a bounded
// number of resolutions and opens (runtime/sa2_files.c), so the record's counts must equal the
// lists' lengths, or the lists are not every file the game touched; the game's file system must
// be ready on the read root and write root given; the relay handed on every byte and frame it took,
// and the player presented every frame the relay handed it.
//
// The game, the installer's verify and the player each run in a process group of their own, so a
// Ctrl-C at the terminal reaches the launcher alone, which stops the game through SIGTERM (the
// host's quit) as above; a second Ctrl-C stops at once (SIGKILL to the game's group, and the
// player cancelled).
//
// The record (--record, a .runrec: never .json, which the M7 census would read as a game run)
// is schema sa2-s7-launch-run/v1; every path in it under $HOME is written with '~'.
